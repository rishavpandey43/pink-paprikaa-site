/**
 * Compiles the brand SVGs (src/assets/brand) into src/lib/brand-artwork.ts and
 * src/lib/brand-artwork.css.
 * Run: pnpm nx run @pink-paprikaa-web/ui:brand-artwork — then commit the output.
 *
 * Only the pink files are compiled: white and badge are the same artwork painted differently
 * (currentColor; a pink plate), so one path set per mark is the whole source of truth. Element ids
 * get an `__ID__` placeholder the Logo replaces per instance, so two logos on a page never share a
 * clip-path id.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { optimize } from "svgo";

const ROOT = new URL("../", import.meta.url);
const SOURCES = {
  lockup: "logo-lockup-pink.svg",
  wordmark: "logo-wordmark-pink.svg",
  symbol: "symbol-pink.svg",
};

/**
 * Two decimal places for path data: it cuts the lockup from ~59 KB to ~38 KB (gzip ~23 → ~15 KB)
 * and renders indistinguishably from the source even at 480px on a 4× screen. One place was
 * measured and rejected: it visibly distorts the hairline lotus ring around the "i" dot (the
 * marks must scale to a 1080px canvas). Numeric attributes (the viewBox, the clip rect) keep
 * svgo's default 3 places so the viewBox stays exactly the source's. `transformPrecision` needs
 * no override: the only transform left is the lockup's integer `translate(165 230)`.
 */
const SVGO_PLUGINS = [
  {
    name: "preset-default",
    params: { floatPrecision: 2, overrides: { cleanupNumericValues: { floatPrecision: 3 } } },
  },
];
const LITERAL_COLOUR = /#[\da-f]{3,8}\b/i;

function compile(file) {
  const source = readFileSync(new URL(`src/assets/brand/${file}`, ROOT), "utf8");
  const { data } = optimize(source, { multipass: true, plugins: SVGO_PLUGINS });
  const viewBox = /viewBox="([^"]+)"/.exec(data)?.[1];
  if (!viewBox) throw new Error(`${file}: no viewBox after optimisation`);
  const [, , width, height] = viewBox.split(/\s+/).map(Number);
  if (!Number.isFinite(width) || !Number.isFinite(height))
    throw new Error(`${file}: viewBox "${viewBox}" has no finite width and height`);
  const markup = data
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/fill="#[\da-f]{3,8}"/gi, 'fill="currentColor"')
    .replace(/id="([^"]+)"/g, 'id="__ID__$1"')
    .replace(/url\(#([^)]+)\)/g, "url(#__ID__$1)");
  if (markup.startsWith("<svg")) throw new Error(`${file}: the root <svg> was not stripped`);
  if (LITERAL_COLOUR.test(markup))
    throw new Error(`${file}: a literal colour survived recolouring`);
  // Only url(#…) references are made instance-safe; an href="#…" would point across instances.
  if (/href="#/.test(markup))
    throw new Error(`${file}: an href="#…" reference is not instance-safe`);
  return { viewBox, width, height, markup };
}

const artwork = Object.fromEntries(
  Object.entries(SOURCES).map(([mark, file]) => [mark, compile(file)])
);

const symbolWhite = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${artwork.symbol.viewBox}" fill="white">${artwork.symbol.markup.replaceAll(' fill="currentColor"', "")}</svg>`;
const symbolDataUri = `url("data:image/svg+xml,${encodeURIComponent(symbolWhite)}")`;

const out = `// Generated by scripts/build-brand-artwork.mjs from src/assets/brand/*.svg — do not edit.
export type Mark = "lockup" | "wordmark" | "symbol";

export interface Artwork {
  readonly viewBox: string;
  readonly width: number;
  readonly height: number;
  /** Inner SVG markup, painted with currentColor; ids carry the __ID__ placeholder. */
  readonly markup: string;
}

export const ARTWORK: Readonly<Record<Mark, Artwork>> = ${JSON.stringify(artwork, null, 2)};
`;

/* The symbol defined once — the only place the white symbol tile exists — for every small diamond
   (SpiceLevel, Rating, StatusDot, Spinner, Divider) and PatternField: inlining its path data per
   instance would bloat a menu page. */
const css = `/* Generated by scripts/build-brand-artwork.mjs — do not edit. */
@layer base {
  :root {
    --pp-symbol-mask: ${symbolDataUri};
  }
}

/* The brand symbol painted in currentColor: <span class="mask-symbol"> with a size. */
@utility mask-symbol {
  background-color: currentColor;
  -webkit-mask: var(--pp-symbol-mask) center / contain no-repeat;
  mask: var(--pp-symbol-mask) center / contain no-repeat;
}
`;

writeFileSync(new URL("src/lib/brand-artwork.ts", ROOT), out);
writeFileSync(new URL("src/lib/brand-artwork.css", ROOT), css);
console.log("brand-artwork.ts + brand-artwork.css written:", Object.keys(artwork).join(", "));
