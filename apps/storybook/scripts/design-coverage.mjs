#!/usr/bin/env node
/**
 * Design coverage map — the "nothing the design defines is removed" check.
 *
 * Reads the Claude Design handoff (`zip-files/Pink Paprikaa Design System/`, read-only) and writes
 * `docs/superpowers/specs/2026-10-04-design-parity/coverage.md`: one table per component, plus one
 * each for guidelines, templates, ui_kits and handoff rules. Every row is
 * `design item | our equivalent | status`.
 *
 * Rows come from: every interface member and exported type in `<Name>.d.ts`, every labelled row
 * (and the `@dsCard` header) in `<Name>.card.html`, the behaviours detected in `<Name>.jsx`
 * (keys, aria, press states, motion, responsive switches), and the matching rows of
 * `handoff/INTERACTIONS.md`.
 *
 * Re-running keeps every cell already filled in (rows are keyed by section + design item), so the
 * script is safe to run again when the handoff changes: new rows come back blank, rows that left
 * the handoff are listed under "Removed from the handoff".
 *
 * Status vocabulary (exactly one of): `have` · `planned in Task <id>` · an approved ruling
 * `R136` `R137` `R140` `R142` `R143` (or any `R1xx` from the plan's rulings table).
 *
 *   node apps/storybook/scripts/design-coverage.mjs           regenerate, keeping filled cells
 *   node apps/storybook/scripts/design-coverage.mjs --check   exit 1 on blank or invalid cells
 *   node apps/storybook/scripts/design-coverage.mjs --fresh   ignore the existing file's cells
 */
import { existsSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

import {
  cell,
  code,
  handoff,
  interactionsFor,
  list,
  norm,
  parseCard,
  parseDts,
  parseJsx,
  read,
  repo,
  splitRow,
} from "./design-coverage-parse.mjs";
import { writeHandoffSections } from "./design-coverage-sections.mjs";

const outFile = join(repo, "docs/superpowers/specs/2026-10-04-design-parity/coverage.md");

const args = new Set(process.argv.slice(2));
const STATUS = /^(have|planned in Task \d+b?|R1\d\d)$/;
const TIERS = ["atoms", "molecules", "organisms", "layouts"];
const ISSUES = [];

// ---------------------------------------------------------------------------------------------
// existing cells (so a re-run never loses hand-written equivalents or statuses)
// ---------------------------------------------------------------------------------------------
function loadExisting() {
  const map = new Map();
  if (args.has("--fresh") || !existsSync(outFile)) return map;
  let section = "";
  for (const line of read(outFile).split("\n")) {
    const heading = /^(#{2,4}) (.+)$/.exec(line);
    if (heading) {
      section = heading[2];
      continue;
    }
    if (section === "Summary") continue;
    if (!line.startsWith("|") || /^\|\s*-/.test(line) || /^\|\s*design item/.test(line)) continue;
    const [item, equivalent, status] = splitRow(line);
    if (item)
      map.set(`${norm(section)}::${norm(item)}`, {
        equivalent: equivalent ?? "",
        status: status ?? "",
      });
  }
  return map;
}
const existing = loadExisting();

const seen = new Set();

// ---------------------------------------------------------------------------------------------
// markdown output model
// ---------------------------------------------------------------------------------------------
const out = [];
const stats = { total: 0, blank: 0, invalid: 0, have: 0, planned: 0, ruling: 0 };

function row(section, item, hint = "") {
  const key = `${norm(section)}::${norm(item)}`;
  seen.add(key);
  const old = existing.get(key);
  const equivalent = old?.equivalent ?? "";
  const status = old?.status ?? "";
  stats.total++;
  if (!equivalent || !status) stats.blank++;
  if (status === "have") stats.have++;
  else if (status.startsWith("planned")) stats.planned++;
  else if (/^R1\d\d$/.test(status)) stats.ruling++;
  if (status && !STATUS.test(status)) stats.invalid++;
  out.push(`| ${item}${hint ? ` ${hint}` : ""} | ${equivalent} | ${status} |`);
}

function table(section, rows) {
  out.push("", "| design item | our equivalent | status |", "| --- | --- | --- |");
  for (const item of [...new Set(rows)]) row(section, item);
  if (rows.length === 0) out.push("| _(no rows)_ | — | have |");
}

// ---------------------------------------------------------------------------------------------
// build
// ---------------------------------------------------------------------------------------------
const componentsDir = join(handoff, "components");
const ixFor = interactionsFor();

out.push(
  "# Design coverage map",
  "",
  "> Generated by `apps/storybook/scripts/design-coverage.mjs` from the Claude Design handoff",
  "> (`zip-files/Pink Paprikaa Design System/`, read-only). Re-running keeps every filled cell.",
  "> `design item | our equivalent (file:symbol or story) | status`.",
  ">",
  "> Status is exactly one of: `have` · `planned in Task <id>` (id from the plan) · an approved ruling:",
  "> `R136` 16px field text · `R137` AA colours · `R140` no egg, no “18 spices”, Instagram only ·",
  "> `R142` Card as a real link, DietMark veg-only · `R143` Typography name.",
  "> Task 12 Step 5 fails the review if any row is not `have` or an approved R-number.",
  "> Paths are relative to `packages/ui/src/` (`UI:`), `apps/storybook/src/` (`SB:`) or the repo root.",
  "",
  "@@SUMMARY@@",
  "",
  "## 1. Components"
);

for (const tier of TIERS) {
  const dir = join(componentsDir, tier);
  const names = list(dir)
    .filter((f) => f.endsWith(".d.ts"))
    .map((f) => f.replace(".d.ts", ""));
  out.push("", `### ${tier[0].toUpperCase()}${tier.slice(1)} (${names.length})`);
  for (const name of names) {
    const section = `${name}`;
    const card = existsSync(join(dir, `${name}.card.html`))
      ? parseCard(join(dir, `${name}.card.html`))
      : undefined;
    const props = parseDts(join(dir, `${name}.d.ts`));
    out.push(
      "",
      `#### ${section}`,
      "",
      `> design: \`components/${tier}/${name}.{d.ts,jsx,card.html,prompt.md}\``
    );
    const items = [...props];
    if (card) {
      items.push(`card ${code(`${card.group}/${card.name}`)} — ${cell(card.subtitle)}`);
      for (const r of card.rows) items.push(`card row — ${cell(r)}`);
    }
    for (const b of parseJsx(join(dir, `${name}.jsx`))) items.push(`jsx ${cell(b)}`);
    for (const ix of ixFor(name)) items.push(`IX ${cell(`${ix.section} / ${ix.text}`)}`);
    table(section, items);
  }
}

writeHandoffSections(out, table);

// removed rows -------------------------------------------------------------------------------
const removed = [...existing.keys()].filter((k) => !seen.has(k));
if (removed.length > 0) {
  out.push("", "## Removed from the handoff since the last run", "");
  for (const key of removed) out.push(`- ${key.replace("::", " → ")}`);
}

const summary = [
  "## Summary",
  "",
  "| status | rows |",
  "| --- | --- |",
  `| have | ${stats.have} |`,
  `| planned in Task N | ${stats.planned} |`,
  `| approved ruling (R-number) | ${stats.ruling} |`,
  `| blank or invalid | ${stats.blank + stats.invalid} |`,
  `| **total** | **${stats.total}** |`,
].join("\n");
const text = `${out.join("\n").replace("@@SUMMARY@@", summary)}\n`;

if (args.has("--check")) {
  const problems = [];
  if (stats.blank > 0) problems.push(`${stats.blank} blank row(s)`);
  if (stats.invalid > 0)
    problems.push(`${stats.invalid} row(s) with a status outside have / planned in Task N / R1xx`);
  if (removed.length > 0) problems.push(`${removed.length} row(s) no longer in the handoff`);
  if (problems.length > 0) {
    console.error(`design-coverage: ${problems.join("; ")}`);
    process.exit(1);
  }
  console.log(`design-coverage: ${stats.total} rows, all filled`);
} else {
  writeFileSync(outFile, text);
  console.log(
    `design-coverage: wrote ${relative(repo, outFile)} — ${stats.total} rows (${stats.blank} blank, ${stats.invalid} invalid)`
  );
}
for (const issue of ISSUES) console.warn(issue);
